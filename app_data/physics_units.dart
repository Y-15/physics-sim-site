PhysicsUnit _unit({
  required String id,
  required String title,
  required String shortLabel,
  required String overview,
  required String everydayExample,
  required String firstStep,
  required List<PhysicsTopic> topics,
}) {
  return PhysicsUnit(
    id: id,
    title: title,
    emoji: shortLabel,
    overview: overview,
    everydayExample: everydayExample,
    firstStep: firstStep,
    topics: topics,
  );
}

PhysicsTopic _topic({
  required String id,
  required String title,
  required String summary,
  required String keyPoint,
  required List<PhysicsLessonSection> sections,
  required List<PhysicsFormula> formulas,
  required List<String> checkpoints,
}) {
  return PhysicsTopic(
    id: id,
    title: title,
    summary: summary,
    keyPoint: keyPoint,
    sections: <PhysicsLessonSection>[
      ...sections,
      ...?kDetailedTopicSections[id],
      ...?kExtendedTopicSections[id],
    ],
    formulas: formulas,
    checkpoints: checkpoints,
  );
}

PhysicsLessonSection _section(
  String title,
  String body, {
  List<PhysicsFormula> formulas = const <PhysicsFormula>[],
}) {
  return PhysicsLessonSection(title: title, body: body, formulas: formulas);
}

PhysicsFormula _formula(
  String title,
  String expression,
  String note, {
  String? latex,
}) {
  return PhysicsFormula(
    title: title,
    expression: expression,
    note: note,
    latex: latex,
  );
}
