List<PhysicsTopic> _buildTopics(List<_TopicSeed> seeds) {
  return seeds.map(_buildTopic).toList(growable: false);
}

PhysicsTopic _buildTopic(_TopicSeed seed) {
  final formula = PhysicsFormula(
    title: seed.formulaTitle,
    expression: seed.expression,
    latex: seed.latex,
    note: seed.formulaNote,
  );
  return PhysicsTopic(
    id: seed.id,
    title: seed.title,
    summary: seed.summary,
    keyPoint: seed.formulaNote,
    sections: <PhysicsLessonSection>[
      PhysicsLessonSection(
        title: '1. 身近な現象と到達目標',
        body: '${seed.summary} 身の回りの現象を、向き・変化・保存のどれに注目するか考えながら説明できることを目標にします。',
      ),
      PhysicsLessonSection(title: '2. 現象のしくみ', body: seed.explanation),
      PhysicsLessonSection(
        title: '3. 基本法則',
        body: seed.formulaNote,
        formulas: <PhysicsFormula>[formula],
      ),
      PhysicsLessonSection(title: '4. 成立条件を確認', body: seed.condition),
      PhysicsLessonSection(
        title: '5. グラフ・観察・実験',
        body: seed.observation,
      ),
      PhysicsLessonSection(
        title: '6. 例題での使い方',
        body:
            '問題文から既知量と未知量を書き出し、正方向と単位を決めます。次に「${seed.formulaTitle}」が使える条件を確認し、記号の式を立ててから数値を代入します。最後に単位・符号・極端な場合を確かめます。',
      ),
      PhysicsLessonSection(
        title: '7. よくある誤解',
        body: seed.mistake,
      ),
      PhysicsLessonSection(
        title: '8. 要点まとめ',
        body:
            '${seed.formulaNote} また、${seed.condition} この2点を自分の言葉で説明できれば、この小単元の基本は完成です。',
      ),
    ],
    formulas: <PhysicsFormula>[formula],
    checkpoints: <String>[
      seed.formulaNote,
      seed.condition,
      seed.mistake,
    ],
  );
}

